USE ROLE ACCOUNTADMIN;   -- or any role with CREATE DATABASE / WAREHOUSE

CREATE WAREHOUSE IF NOT EXISTS PLANTPULSE_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'PlantPulse predictive maintenance & OEE command center';

CREATE DATABASE IF NOT EXISTS PLANTPULSE COMMENT = 'PlantPulse - IT/OT converged maintenance data';
CREATE SCHEMA IF NOT EXISTS PLANTPULSE.OT        COMMENT = 'Operational technology: machine telemetry';
CREATE SCHEMA IF NOT EXISTS PLANTPULSE.ERP       COMMENT = 'Enterprise systems: asset master, CMMS work orders, inventory, production';
CREATE SCHEMA IF NOT EXISTS PLANTPULSE.KNOWLEDGE COMMENT = 'Unstructured maintenance knowledge: manuals, SOPs';
CREATE SCHEMA IF NOT EXISTS PLANTPULSE.ANALYTICS COMMENT = 'Features, ML, search, semantic layer, automation';

USE WAREHOUSE PLANTPULSE_WH;
USE DATABASE PLANTPULSE;

-- ---------- OT ----------
CREATE OR REPLACE TABLE OT.SENSOR_READINGS (
  ASSET_ID        VARCHAR      NOT NULL,
  READING_TS      TIMESTAMP_NTZ NOT NULL,
  VIBRATION_MM_S  FLOAT  COMMENT 'Overall vibration velocity RMS (mm/s)',
  TEMPERATURE_C   FLOAT  COMMENT 'Bearing / housing temperature (deg C)',
  RPM             FLOAT  COMMENT 'Shaft speed',
  CURRENT_A       FLOAT  COMMENT 'Motor phase current (A)'
) CLUSTER BY (ASSET_ID, TO_DATE(READING_TS))
  COMMENT = '10-minute condition-monitoring telemetry from PLC/historian';

-- ---------- ERP / CMMS ----------
